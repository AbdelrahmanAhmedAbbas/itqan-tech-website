import { readFile, writeFile, mkdir } from "node:fs/promises";
import { loadEnv } from "vite";
Object.assign(
  process.env,
  loadEnv(process.env.NODE_ENV || "production", process.cwd(), ""),
);
const { siteConfig: owner } = await import("../src/site.config.ts");
const copy = JSON.parse(await readFile("src/i18n/en.json", "utf8"));
const production =
  process.env.VERCEL_ENV === "production" ||
  process.env.SITE_BUILD_TARGET === "production";
const showPending = !production || owner.flags.showUnresolvedInProduction;
const pending = (key) => (showPending ? owner.confirmations[key] : "");
const money = (n) => "$" + Number(n).toLocaleString("en-US");
const substitute = (text, values) =>
  text
    .replace(/\{(\w+)\}/g, (_, key) => values[key] ?? "")
    .replace(/\s+/g, " ")
    .trim();
const p = owner.pricing;
const values = {
  blueprint: money(p.blueprint),
  build: money(p.buildFrom),
  care: money(p.careMonthlyFrom),
  creditDays: p.creditDays,
  minimumMonths: p.careMinimumMonths,
  blueprintTimeline: owner.approved.blueprintTimeline
    ? `The Blueprint takes ${p.blueprintWeeks}.`
    : pending("blueprintTimeline"),
  buildTimeline: owner.approved.buildTimeline || "",
  ownership: owner.approved.ownership ? "" : pending("ownership"),
};
copy.faq.items = copy.faq.items.map((item) => ({
  ...item,
  answer: substitute(item.answer, values),
}));
if (owner.flags.showWasfa)
  copy.projects.push(
    JSON.parse(await readFile("src/i18n/optional-product.en.json", "utf8")),
  );
copy.projects = copy.projects.map((project) => ({
  ...project,
  name:
    project.type === "own" || owner.flags.showClientNames
      ? project.name
      : project.generic,
  status:
    project.slug === "middlemen-mdos" ? owner.flags.mdosStatus : project.status,
}));
if (!owner.flags.showWasfa) delete copy.work.ownLabel;
const config = {
  name: owner.name,
  alternateName: owner.alternateName,
  domain: owner.domain,
  linkedin: owner.linkedin,
  email: owner.email,
  year: new Date().getUTCFullYear(),
  preview: showPending,
  heroVariant: owner.hero.variant,
  prices: p,
  booking: {
    url: owner.booking.url,
    event: owner.booking.event,
    provider: owner.booking.provider,
  },
  form: {
    endpoint: owner.form.endpoint,
    visitorEndpoint: owner.form.visitorEndpoint,
    showEmailField: owner.flags.showEmailField,
  },
  analytics: owner.analytics,
  legal: {
    privacy: owner.legal.privacy,
    terms: owner.legal.terms,
    updated: owner.legal.updated,
  },
  // Operational setup notes belong in the owner config and README, not visitor copy.
  pending: showPending
    ? Object.fromEntries(
        Object.entries(owner.confirmations).filter(
          ([key]) => !["destination", "buildTimeline", "turnaround"].includes(key),
        ),
      )
    : {},
  approved: owner.approved,
};
await mkdir("src/generated", { recursive: true });
await writeFile(
  "src/generated/site.js",
  `// Generated by scripts/prepare-site.mjs from the owner config and locale files.\nexport const data=${JSON.stringify({ copy, config })};\n`,
);
console.log(
  `Prepared ${showPending ? "preview" : "production"} content: ${copy.projects.length} projects; placeholders ${showPending ? "visible" : "hidden"}.`,
);
